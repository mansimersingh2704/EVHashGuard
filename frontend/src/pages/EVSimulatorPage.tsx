import React, { useEffect, useState } from 'react';
import { api } from '../services/api';
import { JsonViewer } from '../components/JsonViewer';
import { LoadingSpinner } from '../components/LoadingSpinner';
import { AlertBanner } from '../components/AlertBanner';
import { Radio, Play, ShieldAlert, Cpu } from 'lucide-react';

export const EVSimulatorPage: React.FC = () => {
  const [stations, setStations] = useState<any[]>([]);
  const [selectedStation, setSelectedStation] = useState<string>('CS-NORDIC-001');
  const [messageType, setMessageType] = useState<string>('BootNotification');
  const [generatedData, setGeneratedData] = useState<any | null>(null);
  const [loading, setLoading] = useState<boolean>(false);
  const [error, setError] = useState<string | null>(null);

  const messageTypes = [
    'BootNotification',
    'Heartbeat',
    'StatusNotification',
    'Authorize',
    'StartTransaction',
    'StopTransaction',
    'MeterValues',
    'FirmwareStatusNotification',
  ];

  useEffect(() => {
    const loadStations = async () => {
      try {
        const data = await api.getStations();
        setStations(data);
        if (data.length > 0) setSelectedStation(data[0].station_id);
      } catch (err) {
        setError('Failed to load simulated charging stations.');
      }
    };
    loadStations();
  }, []);

  const handleGenerate = async () => {
    setLoading(true);
    setError(null);
    try {
      const data = await api.generateEVMessage(selectedStation, messageType);
      setGeneratedData(data);
    } catch (err: any) {
      setError('Failed to generate EV message. Ensure backend is running.');
    } finally {
      setLoading(false);
    }
  };

  const currentStationInfo = stations.find((s) => s.station_id === selectedStation);

  return (
    <div className="space-y-6">
      {/* Configuration Header Card */}
      <div className="bg-slate-900/60 border border-slate-800 rounded-2xl p-6 shadow-lg">
        <div className="flex items-start justify-between mb-4">
          <div>
            <h3 className="text-lg font-bold text-white flex items-center gap-2">
              <Radio className="w-5 h-5 text-cyan-400" />
              EV Firmware Message Simulator
            </h3>
            <p className="text-xs text-slate-300 mt-1">
              Simulates realistic OCPP 1.6-J messages generated by field charging stations,
              paired with hypothetical vendor-specific legacy MD5 integrity extensions.
            </p>
          </div>
        </div>

        {/* Form Controls */}
        <div className="grid grid-cols-1 md:grid-cols-2 gap-4 mt-4">
          <div>
            <label className="block text-xs font-mono text-slate-400 mb-1.5">
              Select Charging Station Endpoint
            </label>
            <select
              value={selectedStation}
              onChange={(e) => setSelectedStation(e.target.value)}
              className="w-full bg-slate-950 border border-slate-800 rounded-xl p-3 text-xs font-mono text-white focus:outline-none focus:border-cyan-500"
            >
              {stations.map((st) => (
                <option key={st.station_id} value={st.station_id}>
                  {st.station_id} — {st.vendor} ({st.model})
                </option>
              ))}
            </select>
          </div>

          <div>
            <label className="block text-xs font-mono text-slate-400 mb-1.5">
              Select OCPP 1.6 Message Action
            </label>
            <select
              value={messageType}
              onChange={(e) => setMessageType(e.target.value)}
              className="w-full bg-slate-950 border border-slate-800 rounded-xl p-3 text-xs font-mono text-white focus:outline-none focus:border-cyan-500"
            >
              {messageTypes.map((type) => (
                <option key={type} value={type}>
                  {type}
                </option>
              ))}
            </select>
          </div>
        </div>

        {/* Selected Station Telemetry Preview */}
        {currentStationInfo && (
          <div className="mt-4 p-3 rounded-xl bg-slate-950/70 border border-slate-800/80 grid grid-cols-2 sm:grid-cols-4 gap-3 text-xs">
            <div>
              <span className="text-slate-500 block text-[10px] font-mono">VENDOR</span>
              <span className="text-white font-medium">{currentStationInfo.vendor}</span>
            </div>
            <div>
              <span className="text-slate-500 block text-[10px] font-mono">MODEL</span>
              <span className="text-white font-medium">{currentStationInfo.model}</span>
            </div>
            <div>
              <span className="text-slate-500 block text-[10px] font-mono">FIRMWARE</span>
              <span className="text-amber-400 font-mono">{currentStationInfo.firmware_version}</span>
            </div>
            <div>
              <span className="text-slate-500 block text-[10px] font-mono">LOCATION</span>
              <span className="text-slate-300 truncate block">{currentStationInfo.location}</span>
            </div>
          </div>
        )}

        <div className="mt-4 flex justify-end">
          <button
            onClick={handleGenerate}
            disabled={loading}
            className="flex items-center gap-2 px-5 py-2.5 bg-gradient-to-r from-blue-600 to-cyan-600 hover:from-blue-500 hover:to-cyan-500 text-white font-semibold text-xs rounded-xl shadow-lg shadow-cyan-600/20 transition disabled:opacity-50"
          >
            <Play className="w-3.5 h-3.5 fill-current" />
            <span>Generate Simulated Frame</span>
          </button>
        </div>

        {error && <p className="text-xs text-rose-400 font-mono mt-3">{error}</p>}
      </div>

      {loading && <LoadingSpinner label="Constructing OCPP 1.6 payload frame..." />}

      {/* Generated Message Display */}
      {generatedData && (
        <div className="space-y-5">
          <div className="grid grid-cols-1 lg:grid-cols-2 gap-5">
            {/* Standard OCPP Frame */}
            <div>
              <div className="flex items-center justify-between mb-2">
                <h4 className="text-xs font-mono font-bold text-white flex items-center gap-2">
                  <Cpu className="w-4 h-4 text-cyan-400" />
                  STANDARD OCPP 1.6 JSON FRAME
                </h4>
                <span className="text-[10px] px-2 py-0.5 rounded bg-blue-950 border border-blue-800 text-blue-300 font-mono">
                  [MessageType, ID, Action, Payload]
                </span>
              </div>
              <JsonViewer
                data={generatedData.ocpp_message}
                title={`OCPP 1.6 ${generatedData.message_type} Call`}
                maxHeight="max-h-80"
              />
            </div>

            {/* Legacy Vendor Integrity Extension */}
            <div>
              <div className="flex items-center justify-between mb-2">
                <h4 className="text-xs font-mono font-bold text-amber-400 flex items-center gap-2">
                  <ShieldAlert className="w-4 h-4 text-amber-400" />
                  SIMULATED LEGACY INTEGRITY BLOCK
                </h4>
                <span className="text-[10px] px-2 py-0.5 rounded bg-amber-950 border border-amber-800 text-amber-400 font-mono">
                  Vendor Proprietary Extension
                </span>
              </div>
              <JsonViewer
                data={generatedData.legacy_integrity_metadata}
                title="Vendor Integrity Metadata (Out-of-Band)"
                maxHeight="max-h-80"
              />
            </div>
          </div>

          <AlertBanner
            type="info"
            title="Protocol Fidelity & Architectural Boundary"
            message="Notice how the standard OCPP frame ([2, UniqueId, Action, Payload]) remains completely unaltered. The legacy MD5 integrity block is transmitted out-of-band as an external wrapper field. This allows the EVHashGuard SHA-3 Migration Wrapper to intercept and upgrade the integrity layer without breaking the legacy OCPP parser in the CSMS backend."
          />
        </div>
      )}
    </div>
  );
};
